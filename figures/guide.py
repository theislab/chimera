"""Write ``figures/INDEX.md``: one entry per figure of the paper, generated from the manifest.

For every page of ``figures.pdf``: the figure, its key and label, what it shows in plain language, the panel files it
is composed from and the script that draws each of them (``producers.tsv``). The build writes it; run it alone with
``PYTHONPATH=$PWD python -m figures.guide``.
"""

from __future__ import annotations

import csv
import json
import sys
from fnmatch import fnmatchcase

from figures import compose as C

INDEX = C.OUT / "INDEX.md"
NUMBERS = C.ROOT / "numbers.tsv"  # key and printed figure number, written by the manuscript's sync script
PRODUCERS = C.ROOT / "producers.tsv"  # panel files and the script that draws them, kept by hand
PANEL_PREFIX = "figures/panels/"


def numbers() -> dict:
    if not NUMBERS.exists():
        return {}
    with NUMBERS.open() as fh:
        return {r["key"]: r["number"] for r in csv.DictReader(fh, delimiter="\t")}


def producers() -> list:
    """The rows of ``producers.tsv``, one per pattern: (pattern, script, command), in the order of the file."""
    if not PRODUCERS.exists():
        return []
    with PRODUCERS.open() as fh:
        return [(pattern, r["script"], r["command"]) for r in csv.DictReader((ln for ln in fh if not ln.startswith("#")), delimiter="\t")
                for pattern in r["panels"].split()]


def producer(panel_file: str, rows: list | None = None) -> tuple | None:
    """(script, command) of a panel file as the manifest names it (``figures/panels/family/name.pdf`` or a path under
    ``notebooks/figures/``): the first row of ``producers.tsv`` whose pattern matches. None when no row does."""
    key = panel_file[:-4] if panel_file.endswith(".pdf") else panel_file
    key = key[len(PANEL_PREFIX):] if key.startswith(PANEL_PREFIX) else key
    for pattern, script, command in (producers() if rows is None else rows):
        if fnmatchcase(key, pattern):
            return script, command
    return None


def unrecorded(panel_files: list) -> list:
    """Problems of the record of panel scripts: a panel file with no row in ``producers.tsv``, or a row whose script
    does not exist. One line each."""
    rows = producers()
    out = []
    for f in sorted(set(panel_files)):
        got = producer(f, rows)
        if got is None:
            out.append(f"{f}: no row in figures/producers.tsv names the script that draws it")
        elif not (C.REPO / got[0]).exists():
            out.append(f"{f}: figures/producers.tsv names {got[0]}, which does not exist")
    return out


def name(fig: dict, num: dict) -> str:
    n = num.get(fig["key"], "")
    if n:
        return ("Supplementary Figure " if n.startswith("S") else "Figure ") + n
    return f"`{fig['label']}`" + (f", part {fig['part']}" if int(fig["part"]) > 1 else "")


def write_index() -> None:
    man = json.loads((C.OUT / "manifest.json").read_text())
    num = numbers()
    rows, used = producers(), {}
    figs = man["figures"]
    out = ["# Figures of the paper", "",
           "Generated by `figures/build.sh` from `manifest.json`; do not edit. One figure per page of `figures.pdf`, in the order of",
           "the paper. A figure is composed from the panel files listed under it by the spec named in the table",
           "(`python -m figures.compose <key>`). Each panel file is followed by the script that draws it; the commands are in",
           "the table at the end (source: `producers.tsv`), and how panels are made is in `README.md`.", "",
           "| Page | Figure | Key | Title | Size (bp) | Spec |", "|---|---|---|---|---|---|"]
    for f in figs:
        out.append(f"| {f['page']} | {name(f, num)} | `{f['key']}` | {f['title']} | {float(f['width_bp']):.0f} x {float(f['height_bp']):.0f} | `{f['spec']}` |")
    for f in figs:
        out += ["", f"## Page {f['page']}: {f['title']}", "", f"{name(f, num)}, key `{f['key']}`, label `{f['label']}`."]
        if f.get("shows"):
            out += ["", f["shows"]]
        out += ["", "Panels:", ""]
        for p in f["panels"]:
            letters = ", ".join(p["letters"])
            got = producer(p["file"], rows)
            out.append(f"- {('(' + letters + ') ') if letters else ''}`{p['file']}`" + (f", page {p['page']}" if p["page"] != 1 else "")
                       + (f", region {tuple(p['region'])}" if p.get("region") else "") + f", scale {p['scale']:.2f}"
                       + (f"; drawn by `{got[0]}`" if got else "; script not recorded"))
            if got:
                used.setdefault(got, set()).add(p["file"].split("/")[-2])
        if f.get("listed"):
            out += ["", "Not yet in the house style: " + "; ".join(sorted(f["listed"])) + " (see `specs/_allow.py`)."]
    out += ["", "## Panel scripts", "",
            "The scripts that draw the panels of the figures above, with the command that runs each (from the repository root, in the",
            "analysis environment, with `PYTHONPATH` set to the repository root). They read stored runs, caches and result tables.", "",
            "| Script | Command | Panel folders |", "|---|---|---|"]
    for (script, command), families in sorted(used.items()):
        out.append(f"| `{script}` | `{command}` | " + ", ".join(f"`{x}`" for x in sorted(families)) + " |")
    INDEX.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    write_index()
    print("written", INDEX)
    sys.exit(0)
