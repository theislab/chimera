"""Supplementary tables for the revision (T8.4).

  tables/corrections-before-after.tex  every value of the gene-identity correction record (T2.2
                                       ``results/revision/T2_2/before_after.csv``), as a longtable:
                                       reported value, corrected value, and where it appeared.
  tables/benchmark_label_use.tex       label use of every integration method (drafted with T5.4/T5.5);
                                       copied verbatim from the draft passed as ``--label-use``.

    PYTHONPATH=$PWD python -m revision.tasks.T8_4_figures.tables [--label-use PATH]
"""

from __future__ import annotations

import argparse
import math
import re
import shutil
from pathlib import Path

import pandas as pd

from revision.tasks.T8_4_figures import common as cm

SRC = cm.RES / "T2_2" / "before_after.csv"
# Notes that name internal task identifiers, reworded for the reader; meaning unchanged.
NOTE_MAP = {"05 is not in the T2.2 rerun list; the flip table is regenerated when 05 reruns":
            "notebook 05 was not part of the corrected rerun; its flip table is regenerated when it reruns"}
# Ortholog audit (O1): notes beneath rows whose corrected gene rests on species without counts, each
# with its manuscript change label. Key: (cohort, quantity, corrected value).
O1_NOTES = {
    ("test H+Mac", "top_F", "SPINK2 (Δα=+0.29)"): (
        "% @@REV1:NEW@@ Note: SPINK2 has no macaque counts. Why: ortholog audit, the macaque matrix has no "
        "SPINK2 row, so this value rests on a macaque zero. [O1]",
        "no macaque counts: the macaque matrix has no SPINK2 row, so this value rests on a macaque zero; "
        "the label is correct"),
    ("test 3-sp", "top_M", "RPL26 (Δα=-0.12)"): (
        "% @@REV1:NEW@@ Note: RPL26 has no human or macaque counts. Why: ortholog audit, the value rests on "
        "mouse counts alone. [O1]",
        "no human or macaque counts: the value rests on mouse counts alone; the label is correct"),
    ("test 3-sp", "top_F", "SPINK2 (Δα=+0.39)"): (
        "% @@REV1:NEW@@ Note: SPINK2 has no macaque counts. Why: ortholog audit, the macaque matrix has no "
        "SPINK2 row. [O1]",
        "no macaque counts: the macaque matrix has no SPINK2 row, so this value rests on human and mouse"),
}


def tex(s: object) -> str:
    if s is None or (isinstance(s, float) and math.isnan(s)):
        return "--"
    s = str(s)
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in [("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_\allowbreak "), ("{", r"\{"), ("}", r"\}"),
                 ("~", r"$\sim$"), ("^", r"\^{}"), ("§", r"\S{}"), ("Δα", r"$\Delta\alpha$"), ("Δ", r"$\Delta$"),
                 ("α", r"$\alpha$"), ("<", r"$<$"), (">", r"$>$"), ("|", r"$|$")]:
        s = s.replace(a, b)
    return s


def num(v: object) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "--"
    try:
        x = float(v)
    except ValueError:
        return tex(v)
    if x == int(x) and abs(x) >= 1:
        return f"{int(x):,}".replace(",", "{,}")
    if x != 0 and (abs(x) < 1e-3 or abs(x) >= 1e5):
        m, e = f"{x:.2e}".split("e")
        return f"${m}\\times10^{{{int(e)}}}$"
    return f"${x:.4g}$"


def where(loc: str) -> str:
    loc = loc.replace("chimera-manuscript ", "")
    loc = re.sub(r"supplementary_figures:[\d-]+,? ?", "Supplementary figure ", loc)
    loc = re.sub(r"extended_results:\d+", "Extended Results", loc)
    loc = re.sub(r"main\.tex:\d+", "main text", loc)
    loc = loc.replace("Supplementary figure Fig ", "Fig ").replace("Supplementary figure (", "Supplementary figure, panel (")
    loc = re.sub(r"Supplementary figure, panel \((Fig [^)]*)\)", r"\1", loc)
    loc = re.sub(r"^(0\d)( |_)", r"notebook \1\2", loc)
    loc = re.sub(r"; (0\d)", r"; notebook \1", loc)
    return tex(loc)


def corrections_table() -> Path:
    d = pd.read_csv(SRC)
    lines = [
        "% Gene-identity correction record. Generated by chimera/revision/tasks/T8_4_figures/tables.py",
        "% from results/revision/T2_2/before_after.csv; do not edit numbers by hand.",
        r"{\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.045\linewidth} "
        r">{\raggedright\arraybackslash}p{0.19\linewidth} >{\raggedright\arraybackslash}p{0.14\linewidth} "
        r">{\raggedright\arraybackslash}p{0.2\linewidth} *{3}{>{\raggedleft\arraybackslash}p{0.09\linewidth}}@{}}",
        r"\caption[Supplementary table]{Every value affected by the corrected gene identity in the testis and "
        r"cross-tissue analyses, before and after the correction. \emph{Reported}: the value as published or as "
        r"held in the analysis output before the correction; \emph{Reproduced}: the reported value recomputed "
        r"with the old gene identity, where possible; \emph{Corrected}: the value after the correction. "
        r"Claim identifiers refer to the correction record deposited with the code. Notes are given beneath "
        r"the row they qualify.}\label{tab:corrections-before-after}\\",
        r"\toprule",
        r"Claim & Where & Comparison & Quantity & Reported & Reproduced & Corrected \\",
        r"\midrule\endfirsthead",
        r"\toprule Claim & Where & Comparison & Quantity & Reported & Reproduced & Corrected \\ \midrule\endhead",
        r"\bottomrule\endfoot",
    ]
    for r in d.itertuples():
        lines.append(" & ".join([tex(r.claim), where(r.location), tex(r.cohort), tex(r.quantity),
                                 num(r.old_value), num(r.old_reproduced), num(r.new_value)]) + r" \\")
        if isinstance(r.note, str) and r.note.strip():
            lines.append(r"\multicolumn{7}{@{}p{0.84\linewidth}@{}}{\hspace{0.045\linewidth}\emph{Note:} "
                         + tex(NOTE_MAP.get(r.note, r.note)) + r"} \\")
        if (r.cohort, r.quantity, r.new_value) in O1_NOTES:
            label, note = O1_NOTES[(r.cohort, r.quantity, r.new_value)]
            lines += [label, r"\multicolumn{7}{@{}p{0.84\linewidth}@{}}{\hspace{0.045\linewidth}\emph{Note:} "
                      + tex(note) + r"} \\"]
    assert sum(any(k == (r.cohort, r.quantity, r.new_value) for r in d.itertuples()) for k in O1_NOTES) == len(O1_NOTES)
    lines += [r"\end{longtable}", "}"]
    out = cm.TAB_OUT / "corrections-before-after.tex"
    out.write_text("\n".join(lines) + "\n")
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--label-use", type=Path, default=None)
    a = ap.parse_args()
    print(corrections_table())
    if a.label_use:
        dst = cm.TAB_OUT / "benchmark_label_use.tex"
        shutil.copyfile(a.label_use, dst)
        print(dst)


if __name__ == "__main__":
    main()
